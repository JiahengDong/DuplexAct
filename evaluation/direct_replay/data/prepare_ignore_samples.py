"""
evaluation/prepare_ignore_samples.py
=====================================
Convert synthesized ignore dialogue data into the standardised sample-folder
layout required by the ignore evaluation rubric.

Two L3 conditions, both using synthesized data:

  ignore_background_speech_during_user_speech   (200 samples, 50/setting)
  ignore_other_directed_speech_during_user_speech (200 samples, 50/setting)

--------------------------------------------------------------
INTERACTION DESIGN
--------------------------------------------------------------

Background condition
  Speaker A is talking to the model (speaker B).  In the background, a
  separate voice (other speaker) is speaking.  The audio presented to the
  model is speaker_a_with_background.wav -- the blended mix already produced
  by tts_synthesize.py.

  B_i: model must NOT speak during the user's foreground speech interval
       [0, speaker_a_duration].

Other-directed condition
  Speaker A is talking to the model and, mid-speech, briefly addresses a
  third person (side speech).  The input is a single-pass speaker_a.wav.
  side_speech_start_s and side_speech_end_s (clip-relative, before padding)
  mark the side-speech window.

  B_i: model must NOT speak during [0, speaker_a_duration].

In both conditions the model is expected to respond *after* the user finishes
(i.e. in the 15 s silence padding).

--------------------------------------------------------------
Output layout (per sample):
    <out_dir>/
      <l3_condition>/
        <sample_id>/
          input.wav       <- user audio (16 kHz mono) + 15 s silence padding
          metadata.json   <- all evaluation context
          [output.wav]    <- generated by inference (not created here)
--------------------------------------------------------------
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Optional

import numpy as np
import soundfile as sf
import librosa

# -- Constants -----------------------------------------------------------------
PADDING_S   = 15.0
TARGET_SR   = 16_000
SETTINGS    = ["casual_conversation", "customer_service", "interview", "meeting"]


def _duplexact_root() -> Path:
    import os
    for key in ("DUPLEXACT_ROOT", "BENCH_ROOT"):
        v = os.environ.get(key)
        if v:
            return Path(v).resolve()
    here = Path(__file__).resolve()
    for p in here.parents:
        if (p / "evaluation" / "paths.py").exists():
            return p
    return here.parents[min(3, len(here.parents)-1)]

SYNTH_BASE  = _duplexact_root() / "data_synthesize" / "ignore"
OUT_BASE    = _duplexact_root() / "evaluation" / "direct_replay" / "data" / "ignore"

L3_CONFIG = {
    "ignore_background_speech_during_user_speech": {
        "short": "bg",
        "input_file": "speaker_a_with_background.wav",
    },
    "ignore_other_directed_speech_during_user_speech": {
        "short": "od",
        "input_file": "speaker_a.wav",
    },
}


# -- Audio helpers --------------------------------------------------------------

def _load_and_resample(path: Path) -> tuple[np.ndarray, int]:
    data, sr = sf.read(str(path), dtype="float32", always_2d=False)
    if data.ndim == 2:
        data = data.mean(axis=1)
    if sr != TARGET_SR:
        data = librosa.resample(data, orig_sr=sr, target_sr=TARGET_SR)
    return data, TARGET_SR


def _pad_silence(audio: np.ndarray, sr: int, pad_s: float) -> np.ndarray:
    silence = np.zeros(int(pad_s * sr), dtype=np.float32)
    return np.concatenate([audio, silence])


def _write_wav(path: Path, data: np.ndarray, sr: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    sf.write(str(path), data, sr)


# -- Transcript helpers ---------------------------------------------------------

def _load_transcript(sample_dir: Path) -> dict:
    p = sample_dir / "transcript.json"
    if p.exists():
        return json.loads(p.read_text())
    return {}


def _extract_texts(transcript: dict) -> dict[str, str]:
    """Return per-role concatenated text from a transcript dialogue list."""
    texts: dict[str, list[str]] = {}
    for turn in transcript.get("dialogue", []):
        spk = turn.get("speaker", "")
        texts.setdefault(spk, []).append(turn.get("text", "").strip())
    return {spk: " ".join(parts) for spk, parts in texts.items()}


# -- Per-condition preparation --------------------------------------------------

def prepare_condition(
    l3_condition: str,
    out_dir: Path,
    overwrite: bool,
    dry_run: bool,
) -> list[dict]:
    cfg        = L3_CONFIG[l3_condition]
    short      = cfg["short"]
    input_file = cfg["input_file"]
    synth_dir  = SYNTH_BASE / l3_condition

    manifest_entries: list[dict] = []
    idx = 0

    for setting in SETTINGS:
        setting_dir = synth_dir / setting
        if not setting_dir.exists():
            print(f"  [WARN] Missing setting dir: {setting_dir}", file=sys.stderr)
            continue

        sample_uuids = sorted(
            d.name for d in setting_dir.iterdir()
            if d.is_dir() and not d.name.startswith("__")
        )

        for uuid in sample_uuids:
            src_dir = setting_dir / uuid
            audio_src = src_dir / input_file
            meta_src  = src_dir / "tts_metadata.json"

            if not audio_src.exists():
                print(f"  [WARN] Missing {input_file}: {src_dir}", file=sys.stderr)
                continue
            if not meta_src.exists():
                print(f"  [WARN] Missing tts_metadata.json: {src_dir}", file=sys.stderr)
                continue

            tts_meta = json.loads(meta_src.read_text())
            transcript = _load_transcript(src_dir)
            texts = _extract_texts(transcript)

            sample_id  = f"ignore_{short}_{idx:04d}"
            sample_out = out_dir / l3_condition / sample_id

            if sample_out.exists() and not overwrite and not dry_run:
                manifest_entries.append({
                    "sample_id":    sample_id,
                    "l3_condition": l3_condition,
                    "dataset":      "synthesized",
                    "setting":      setting,
                    "sample_dir":   str(sample_out),
                })
                idx += 1
                continue

            # -- Load and pad audio -------------------------------------------
            audio, sr = _load_and_resample(audio_src)
            speaker_a_duration = round(len(audio) / sr, 4)
            padded = _pad_silence(audio, sr, PADDING_S)
            input_duration = round(len(padded) / sr, 4)

            # -- Side-speech timestamps (other_directed only) -----------------
            side_speech_start_s: Optional[float] = None
            side_speech_end_s:   Optional[float] = None
            if l3_condition == "ignore_other_directed_speech_during_user_speech":
                for f in tts_meta.get("files", []):
                    if f["label"] == "speaker_a":
                        side_speech_start_s = f.get("side_speech_start_s")
                        side_speech_end_s   = f.get("side_speech_end_s")

            # -- Background speech timestamps (background only) ----------------
            bg_speech_start_s: Optional[float] = None
            bg_speech_end_s:   Optional[float] = None
            if l3_condition == "ignore_background_speech_during_user_speech":
                tts_sr = tts_meta.get("sample_rate", 24000)
                files_by_label = {f["label"]: f for f in tts_meta.get("files", [])}
                bg_entry  = files_by_label.get("speaker_a_with_background", {})
                raw_entry = files_by_label.get("other_raw", {})
                offset_samples = bg_entry.get("mix_offset_samples")
                if offset_samples is not None:
                    bg_speech_start_s = round(offset_samples / tts_sr, 4)
                    other_raw_path = src_dir / raw_entry.get("file", "other_raw.wav")
                    if other_raw_path.exists():
                        other_arr, other_sr = sf.read(str(other_raw_path),
                                                      dtype="float32",
                                                      always_2d=False)
                        other_dur = len(other_arr) / other_sr
                        bg_speech_end_s = round(bg_speech_start_s + other_dur, 4)

            # -- Build metadata -----------------------------------------------
            meta: dict = {
                "task_type":            "ignore",
                "l3_condition":         l3_condition,
                "dataset":              "synthesized",
                "setting":              setting,
                "source_uuid":          uuid,
                "model_role":           "speaker_b",
                "speaker_a_duration":   speaker_a_duration,
                "padding_time":         PADDING_S,
                "input_duration":       input_duration,
                "speaker_a_text":       texts.get("speaker_a", ""),
                "other_text":           texts.get("other", ""),
                "speaker_b_text":       texts.get("speaker_b", ""),
            }
            if l3_condition == "ignore_other_directed_speech_during_user_speech":
                meta["side_speech_start_s"] = side_speech_start_s
                meta["side_speech_end_s"]   = side_speech_end_s
            if l3_condition == "ignore_background_speech_during_user_speech":
                meta["bg_speech_start_s"] = bg_speech_start_s
                meta["bg_speech_end_s"]   = bg_speech_end_s

            if dry_run:
                manifest_entries.append({
                    "sample_id":    sample_id,
                    "l3_condition": l3_condition,
                    "dataset":      "synthesized",
                    "setting":      setting,
                    "sample_dir":   str(sample_out),
                })
                idx += 1
                continue

            sample_out.mkdir(parents=True, exist_ok=True)
            _write_wav(sample_out / "input.wav", padded, sr)
            (sample_out / "metadata.json").write_text(
                json.dumps(meta, indent=2, ensure_ascii=False)
            )

            manifest_entries.append({
                "sample_id":    sample_id,
                "l3_condition": l3_condition,
                "dataset":      "synthesized",
                "setting":      setting,
                "sample_dir":   str(sample_out),
            })
            idx += 1

        if not dry_run:
            print(f"  [{l3_condition}/{setting}] {len([e for e in manifest_entries if e['setting']==setting])} samples")

    return manifest_entries


# -- Main ----------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Prepare ignore evaluation sample folders.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument(
        "--out_dir", type=Path, default=OUT_BASE,
        help="Root output directory (default: evaluation/data/ignore)",
    )
    parser.add_argument(
        "--condition", nargs="+",
        default=list(L3_CONFIG.keys()),
        choices=list(L3_CONFIG.keys()) + ["all"],
        help="Which L3 condition(s) to prepare (default: all)",
    )
    parser.add_argument("--overwrite", action="store_true")
    parser.add_argument("--dry_run",   action="store_true",
                        help="Count samples without writing files")
    args = parser.parse_args()

    conditions = list(L3_CONFIG.keys()) if "all" in args.condition else args.condition

    all_entries: list[dict] = []
    for cond in conditions:
        print(f"\nPreparing: {cond}")
        entries = prepare_condition(
            l3_condition=cond,
            out_dir=args.out_dir,
            overwrite=args.overwrite,
            dry_run=args.dry_run,
        )
        all_entries.extend(entries)
        action = "Found" if args.dry_run else "Wrote"
        print(f"  -> {action} {len(entries)} samples")

    total = len(all_entries)
    if args.dry_run:
        # Summary by condition
        from collections import Counter
        by_cond = Counter(e["l3_condition"] for e in all_entries)
        print("\n[dry_run] Summary:")
        for cond, n in sorted(by_cond.items()):
            print(f"  {cond}: {n}")
        print(f"  TOTAL: {total}")
        print("[dry_run] No files written.")
        return

    manifest_path = args.out_dir / "manifest.json"
    manifest_path.write_text(json.dumps(all_entries, indent=2, ensure_ascii=False))
    print(f"\nTotal: {total} samples")
    print(f"Manifest -> {manifest_path}")


if __name__ == "__main__":
    main()
